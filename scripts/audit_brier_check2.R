options(stringsAsFactors = FALSE, warn = -1)
suppressMessages({library(survival); library(rms); library(data.table)})
ROOT <- "F:/0000_Bioinfo/222_tcgaSHAP_胶质瘤"; setwd(ROOT)
risk <- read.table("04_results/20.SHAP/risk.TCGA.txt", header = TRUE, sep = "\t", check.names = FALSE, row.names = 1)
cli <- read.table("02_inputs/clinical_glioma.txt", header = TRUE, sep = "\t", check.names = FALSE)
d <- merge(data.frame(patient = rownames(risk), risk, check.names = FALSE), cli[, c("patient","age","sex","grade","idh")], by = "patient")
d$Grade <- factor(d$grade); d$IDH <- factor(d$idh); units(d$futime) <- "Year"
dd <- datadist(d); options(datadist = "dd")
f <- cph(Surv(futime, fustat) ~ riskScore + age + Grade + IDH, data = d, x = TRUE, y = TRUE, surv = TRUE)
sv <- survest(f, times = c(1, 3, 5), newdata = d)
cat("class:", class(sv), "\n"); cat("names:", names(sv), "\n"); cat("dim surv:", if (!is.null(sv$surv)) dim(sv$surv) else "NULL", "\n")
print(head(sv, 3))
cat("\n-- basehaz 法对照 --\n")
bh <- basehaz(f, centered = FALSE)
H0 <- approx(bh$time, bh$hazard, xout = c(1, 3, 5), rule = 2)$y
lp <- predict(f, type = "lp")
S_it <- exp(-outer(exp(lp), H0))
cat("预测生存率（前 3 例）:\n"); print(round(S_it[1:3, ], 3))
cat("与 survest 的差异（若 survest 正常应接近 0）:\n")
if (!is.null(sv$surv)) print(round(max(abs(S_it - as.matrix(sv$surv))), 4))
